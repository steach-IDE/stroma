// DSIR -> Flutter package. Pure: the same DSIR, mapping and templates give the same bytes.
import 'dart:convert';

import 'package:dart_style/dart_style.dart';

/// Thrown when the DSIR holds something this emitter cannot print. Never ignored.
class EmitException implements Exception {
  EmitException(this.message);
  final String message;
  @override
  String toString() => 'EmitException: $message';
}

final _formatter = DartFormatter(
  languageVersion: DartFormatter.latestLanguageVersion,
  pageWidth: 100,
);

/// kebab-case -> lowerCamelCase: `primary-foreground` -> `primaryForeground`.
String camel(String kebab) {
  final parts = kebab.split('-');
  return parts.first + parts.skip(1).map((p) => p[0].toUpperCase() + p.substring(1)).join();
}

/// A cva option as a Dart enum value. `default` is a Dart keyword, so it is named `regular`.
String enumValue(String option) => option == 'default' ? 'regular' : camel(option);

String _upperFirst(String s) => s[0].toUpperCase() + s.substring(1);
String _snake(String pascal) =>
    pascal.replaceAllMapped(RegExp('([a-z0-9])([A-Z])'), (m) => '${m[1]}_${m[2]}').toLowerCase();

String _num(num v) => v == v.roundToDouble() ? v.toInt().toString() : v.toString();
String _fixed(double v) => _num(double.parse(v.toStringAsFixed(4)));

Map<String, String> emitPackage({
  required Map<String, dynamic> dsir,
  required Map<String, dynamic> mapping,
  required Map<String, String> templates,
  required String packageName,
}) {
  final components = (dsir['components'] as List).cast<Map<String, dynamic>>();
  final globals = (dsir['globals'] as Map).cast<String, dynamic>();
  final out = <String, String>{};
  String dart(String src) => _formatter.format(src);

  out['pubspec.yaml'] = _pubspec(packageName);
  // scrib/ holds the adapter an app copies in; it only resolves inside a Scrib app.
  out['analysis_options.yaml'] =
      'include: package:flutter_lints/flutter.yaml\n\nanalyzer:\n  exclude:\n    - scrib/**\n';
  out['lib/src/tokens.dart'] = dart(_tokens(dsir, packageName));
  for (final entry in templates.entries) {
    final text = entry.value.replaceAll('{{package}}', packageName);
    out[entry.key] = entry.key.endsWith('.dart') ? dart(text) : text;
  }

  final files = <String, List<Map<String, dynamic>>>{};
  for (final c in components) {
    // CardHeader, CardTitle, ... live in card.dart, as they do in card.tsx.
    final file = _snake(RegExp('^[A-Z][a-z]+').firstMatch(c['name'] as String)!.group(0)!);
    (files[file] ??= []).add(c);
  }
  for (final entry in files.entries) {
    out['lib/src/components/${entry.key}.dart'] = dart(_componentFile(entry.value, globals));
  }
  out['lib/$packageName.dart'] = dart(
    [
      '/// Generated from ${dsir['source']['url']} (${dsir['source']['license']}). Do not edit.',
      'library;',
      '',
      "export 'src/primitives/ds_style.dart' show DsColor;",
      "export 'src/theme.dart';",
      "export 'src/tokens.dart';",
      for (final f in files.keys) "export 'src/components/$f.dart';",
    ].join('\n'),
  );
  out['scrib/scrib_adapter.dart'] = dart(_scribAdapter(mapping, packageName));
  out['test/oracle/cells.json'] =
      '${const JsonEncoder.withIndent('  ').convert(oracleCells(components))}\n';
  return out;
}

