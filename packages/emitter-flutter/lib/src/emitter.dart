String _switch(String scribEnum, Map<String, dynamic> values, String target) {
  final cases = values.entries
      .map((e) => '$scribEnum.${e.key} => $target.${enumValue(e.value as String)},')
      .join('\n');
  return 'switch (variant) {\n$cases\n}';
}

