// ---------------- tokens ----------------

String _fontFamily(Map<String, dynamic> dsir) =>
    (((dsir['tokens'] as Map)['font'] as Map?)?['sans'] as Map?)?['family'] as String? ?? 'Inter';

/// The DSIR's modes (theme names): light and dark first, then the rest in name order.
List<String> _modes(Map<String, dynamic> dsir) {
  final colors = ((dsir['tokens'] as Map)['color'] as Map).cast<String, dynamic>();
  final all = {for (final t in colors.values) ...(t as Map).keys.cast<String>()}.toList()..sort();
  return [
    ...['light', 'dark'].where(all.contains),
    ...all.where((m) => m != 'light' && m != 'dark'),
  ];
}

/// The tokens that paint the page and its text. A DSIR does not name them, so they are found by name:
/// `background` or the shortest `*-background`; `foreground`, `*-text-primary` or `*-foreground`.
/// shortcut: a naming convention, when a design system uses another a DSIR needs explicit page roles.
(String background, String foreground) _pageTokens(Map<String, dynamic> dsir) {
  final names = (((dsir['tokens'] as Map)['color'] as Map).keys.cast<String>()).toList()..sort();
  String? find(List<String> exact, List<String> suffixes) {
    for (final n in names) {
      if (exact.contains(n)) return n;
    }
    for (final suffix in suffixes) {
      final hits = names.where((n) => n.endsWith(suffix)).toList()
        ..sort((a, b) => a.length - b.length);
      if (hits.isNotEmpty) return hits.first;
    }
    return null;
  }

  final bg = find(['background'], ['-background']);
  final fg = find(['foreground'], ['-text-primary', '-foreground']);
  if (bg == null || fg == null) {
    throw EmitException(
      'no page ${bg == null ? 'background' : 'foreground'} token: name one `background` or `foreground`',
    );
  }
  return (bg, fg);
}

/// How light a mode's page is, 0 (black) to 1 (white). A mode with no page background there counts as light.
double _pageLuminance(String mode, Map<String, dynamic> dsir) {
  final bg = (((dsir['tokens'] as Map)['color'] as Map)[_pageTokens(dsir).$1] as Map)[mode] as Map?;
  if (bg == null) return 1;
  final rgb = [1, 3, 5].map((i) => int.parse((bg['hex'] as String).substring(i, i + 2), radix: 16));
  final l = rgb.map((v) {
    final c = v / 255;
    return c <= 0.03928 ? c / 12.92 : math.pow((c + 0.055) / 1.055, 2.4).toDouble();
  }).toList();
  return 0.2126 * l[0] + 0.7152 * l[1] + 0.0722 * l[2];
}

/// `dark` for a mode named so, or one whose page background is dark; every other mode is light.
bool _isDark(String mode, Map<String, dynamic> dsir) =>
    mode == 'dark' || (mode != 'light' && _pageLuminance(mode, dsir) < 0.5);

String _colorLiteral(String hex, num alpha) {
  final rgb = hex.substring(1).toUpperCase();
  if (alpha == 1) return 'Color(0xFF$rgb)';
  double ch(int i) => int.parse(rgb.substring(i, i + 2), radix: 16) / 255;
  return 'Color.from(alpha: ${_num(alpha)}, red: ${_fixed(ch(0))}, green: ${_fixed(ch(2))}, blue: ${_fixed(ch(4))})';
}

String _tokens(Map<String, dynamic> dsir, String packageName) {
  final tokens = dsir['tokens'] as Map<String, dynamic>;
  final colors = (tokens['color'] as Map).cast<String, dynamic>();
  // A design system with no radius tokens (Carbon's corners are square) has a base of 0 and nothing derived.
  final radius = (tokens['radius'] as Map?)?.cast<String, dynamic>() ?? const {'base': 0};
  final names = colors.keys.toList();
  final fields = names.map(camel).toList();
  final modes = _modes(dsir);
  final (pageBg, pageFg) = _pageTokens(dsir);
  final b = StringBuffer()
    ..writeln('// Generated from the DSIR tokens (DTCG files in dsir/tokens/). Do not edit.')
    ..writeln("import 'package:flutter/material.dart';")
    ..writeln()
    ..writeln(
      '/// Design tokens for one mode. Colours are sRGB conversions of the source OKLCH values.',
    )
    ..writeln('@immutable')
    ..writeln('class DsTokens extends ThemeExtension<DsTokens> {')
    ..writeln('  const DsTokens({')
    ..writeln('    required this.mode,')
    ..writeln('    required this.brightness,');
  for (final f in fields) {
    b.writeln('    required this.$f,');
  }
  b
    ..writeln('    this.radius = ${_num(radius['base'] as num)},')
    ..writeln("    this.fontFamily = '${_fontFamily(dsir)}',")
    ..writeln("    this.fontPackage = '$packageName',")
    ..writeln('  });')
    ..writeln()
    ..writeln('  /// The theme this set is for, as the design system names it.')
    ..writeln('  final String mode;')
    ..writeln('  final Brightness brightness;');
  for (var i = 0; i < names.length; i++) {
    b
      ..writeln('  /// `--${names[i]}`')
      ..writeln('  final Color ${fields[i]};');
  }
  b
    ..writeln()
    ..writeln(
      "  /// `--radius`. The scale below derives from it, as shadcn's `@theme inline` does.",
    )
    ..writeln('  final double radius;')
    ..writeln('  final String fontFamily;')
    ..writeln('  final String? fontPackage;');
  final derived = ((radius['derived'] as Map?) ?? const {}).cast<String, dynamic>();
  for (final e in derived.entries) {
    final d = e.value as num;
    final expr = d == 0 ? 'radius' : (d > 0 ? 'radius + ${_num(d)}' : 'radius - ${_num(-d)}');
    b
      ..writeln(
        '  /// `--radius-${e.key}`: calc(var(--radius) ${d >= 0 ? '+' : '-'} ${_num(d.abs())}px)',
      )
      ..writeln('  double get radius${_upperFirst(e.key)} => $expr;');
  }
  b
    ..writeln()
    ..writeln(
      "  /// What components inherit from `body`: the browser's 16px, preflight's line-height",
    )
    ..writeln("  /// 1.5, and `text-foreground` from the style's base layer.")
    ..writeln('  TextStyle get bodyText => TextStyle(')
    ..writeln('        fontFamily: fontFamily,')
    ..writeln('        package: fontPackage,')
    ..writeln('        fontSize: 16,')
    ..writeln('        height: 1.5,')
    ..writeln('        fontWeight: FontWeight.w400,')
    ..writeln('        color: ${camel(pageFg)},')
    ..writeln('        leadingDistribution: TextLeadingDistribution.even,')
    ..writeln('        decoration: TextDecoration.none,')
    ..writeln('      );')
    ..writeln();
  for (final mode in modes) {
    b
      ..writeln('  static const ${camel(mode)} = DsTokens(')
      ..writeln("    mode: '$mode',")
      ..writeln('    brightness: Brightness.${_isDark(mode, dsir) ? 'dark' : 'light'},');
    for (var i = 0; i < names.length; i++) {
      // A token no cell used in one mode has no measured value there; no rule can read it, so it
      // borrows the other mode's value and says so.
      final byMode = (colors[names[i]] as Map).cast<String, dynamic>();
      final measured = byMode[mode] as Map<String, dynamic>?;
      final v = (measured ?? byMode.values.first) as Map<String, dynamic>;
      b.writeln(
        '    ${fields[i]}: ${_colorLiteral(v['hex'] as String, v['alpha'] as num)},'
        '${measured == null ? ' // not measured in $mode: no rule reads it there' : ''}',
      );
    }
    b
      ..writeln('  );')
      ..writeln();
  }
  // The ambient theme picks by brightness: the lightest light mode and the darkest dark one (or the first mode).
  double lum(String m) => _pageLuminance(m, dsir);
  final lights = modes.where((m) => !_isDark(m, dsir)).toList()
    ..sort((a, b) => lum(b).compareTo(lum(a)));
  final darks = modes.where((m) => _isDark(m, dsir)).toList()
    ..sort((a, b) => lum(a).compareTo(lum(b)));
  final light = lights.isEmpty ? modes.first : lights.first;
  final dark = darks.isEmpty ? light : darks.first;
  if (!modes.contains('light')) b.writeln('  static const light = ${camel(light)};');
  if (!modes.contains('dark')) b.writeln('  static const dark = ${camel(dark)};');
  b
    ..writeln('  static const all = [${modes.map(camel).join(', ')}];')
    ..writeln()
    ..writeln('  static DsTokens byMode(String mode) => all.firstWhere((t) => t.mode == mode);')
    ..writeln()
    ..writeln('  /// What paints the page, and its text.')
    ..writeln('  Color get pageBackground => ${camel(pageBg)};')
    ..writeln('  Color get pageForeground => ${camel(pageFg)};')
    ..writeln()
    ..writeln('  @override')
    ..writeln(
      '  DsTokens copyWith({Brightness? brightness, ${fields.map((f) => 'Color? $f').join(', ')}, double? radius}) => DsTokens(',
    )
    ..writeln('    mode: mode,')
    ..writeln('    brightness: brightness ?? this.brightness,');
  for (final f in fields) {
    b.writeln('    $f: $f ?? this.$f,');
  }
  b
    ..writeln('    radius: radius ?? this.radius,')
    ..writeln('    fontFamily: fontFamily,')
    ..writeln('    fontPackage: fontPackage,')
    ..writeln('  );')
    ..writeln()
    ..writeln('  @override')
    ..writeln('  DsTokens lerp(DsTokens? other, double t) {')
    ..writeln('    if (other == null) return this;')
    ..writeln('    return DsTokens(')
    ..writeln('      mode: t < 0.5 ? mode : other.mode,')
    ..writeln('      brightness: t < 0.5 ? brightness : other.brightness,');
  for (final f in fields) {
    b.writeln('      $f: Color.lerp($f, other.$f, t)!,');
  }
  b
    ..writeln('      radius: radius + (other.radius - radius) * t,')
    ..writeln('      fontFamily: fontFamily,')
    ..writeln('      fontPackage: fontPackage,')
    ..writeln('    );')
    ..writeln('  }')
    ..writeln('}');
  return b.toString();
}

// ---------------- components ----------------

String _colorRef(Map<String, dynamic> c) {
  if (c['transparent'] == true) return 'Color(0x00000000)';
  final alpha = c['alpha'] as num;
  if (c['hex'] != null) return _colorLiteral(c['hex'] as String, alpha);
  final ref = 't.${camel(c['token'] as String)}';
  return alpha == 1 ? ref : '$ref.scaleAlpha(${_num(alpha)})';
}

/// CSS blur radius is two standard deviations; Flutter maps blurRadius to sigma as r * 0.57735 + 0.5.
String _shadow(Map<String, dynamic> s) {
  final cssSigma = (s['blur'] as num) / 2;
  final blur = cssSigma <= 0.5 ? 0.0 : (cssSigma - 0.5) / 0.57735;
  final c = s['color'] as Map<String, dynamic>;
  final rgb = (c['rgb'] as List).cast<num>();
  return 'BoxShadow(offset: Offset(${_num(s['x'] as num)}, ${_num(s['y'] as num)}), '
      'blurRadius: ${_fixed(blur)}, spreadRadius: ${_num(s['spread'] as num)}, '
      'color: Color.from(alpha: ${_num(c['alpha'] as num)}, red: ${_fixed(rgb[0] / 255)}, '
      'green: ${_fixed(rgb[1] / 255)}, blue: ${_fixed(rgb[2] / 255)}))';
}

String _cubic(String css) {
  final m = RegExp(r'cubic-bezier\(([^)]+)\)').firstMatch(css);
  if (m == null) throw EmitException('unknown timing function $css');
  return 'Cubic(${m[1]!.split(',').map((x) => _num(num.parse(x.trim()))).join(', ')})';
}

/// One DSIR `set` as DsStyle constructor arguments, and whether they are all constant.
(String, bool) _styleArgs(Map<String, dynamic> set) {
  final args = <String>[];
  var isConst = true;
  void color(String field, Object? v) {
    final ref = _colorRef((v as Map).cast<String, dynamic>());
    if (ref.startsWith('t.')) isConst = false;
    args.add('$field: $ref');
  }

  void number(String field, Object? v) => args.add('$field: ${_num(v as num)}');

  for (final e in set.entries) {
    final v = e.value;
    switch (e.key) {
      case 'layout':
        args.add('layout: DsLayout.$v');
      case 'crossAlign':
        args.add('crossAlign: DsAlign.$v');
      case 'mainAlign':
        args.add('mainAlign: DsAlign.$v');
      case 'gap' || 'opacity' || 'fontSize' || 'borderWidth' || 'ringWidth':
        number(e.key, v);
      case 'h':
        number('height', v);
      case 'w':
        number('width', v);
      case 'px':
        number('paddingX', v);
      case 'py':
        number('paddingY', v);
      case 'pt':
        number('paddingTop', v);
      case 'pb':
        number('paddingBottom', v);
      case 'lineHeightFactor':
        number('lineHeight', v);
      case 'fontWeight':
        args.add('fontWeight: FontWeight.w$v');
      case 'maxLines':
        args.add('maxLines: $v');
      case 'underline' || 'clip':
        args.add('${e.key}: $v');
      case 'bg':
        color('background', v);
      case 'fg':
        color('foreground', v);
      case 'borderColor':
        color('borderColor', v);
      case 'ringColor':
        color('ringColor', v);
      case 'radius' when v is num:
        // A measured corner that matches no token (inferred DSIRs).
        args.add('radius: ${_num(v)}');
      case 'radius':
        final r = (v as Map).cast<String, dynamic>();
        if (r['full'] == true) {
          args.add('radius: 9999');
        } else {
          isConst = false;
          args.add(
            'radius: t.radius${_upperFirst((r['token'] as String).replaceFirst('radius-', ''))}',
          );
        }
      case 'shadow':
        // CSS paints the first shadow on top; Flutter paints the list in order, last on top.
        final list = (v as List).cast<Map<String, dynamic>>().reversed.map(_shadow).join(', ');
        args.add('shadows: [$list]');
      case 'transitionMs':
        args.add('transition: Duration(milliseconds: ${_num(v as num)})');
      case 'transitionCurve':
        args.add('curve: ${_cubic(v as String)}');
      case 'columns':
        // The one grid this emitter lays out: 1fr content plus an auto trailing column (DsBox.trailing).
        if ((v as List).join(' ') != '1fr auto') {
          throw EmitException('grid columns ${v.join(' ')} have no Flutter layout here');
        }
      default:
        throw EmitException('DSIR style key "${e.key}" has no Flutter mapping');
    }
  }
  return (args.join(', '), isConst);
}

String _enumName(Map<String, dynamic> c, String axis) => '${c['name']}${_upperFirst(axis)}';
Map<String, dynamic> _variants(Map<String, dynamic> c) =>
    (c['variants'] as Map).cast<String, dynamic>();

/// A part slot's widget field: `card-action` in a `card-header` is `action`. A DSIR names a slot by `name`
/// (source-derived: `action`) or by `dataSlot` (inferred: `card-action`); both resolve to the same field.
String? _partField(Map<String, dynamic> c, String ref) {
  for (final s in (c['slots'] as List).cast<Map<String, dynamic>>()) {
    final data = s['dataSlot'] as String?;
    if (data == null || (s['name'] != ref && data != ref)) continue;
    final prefix = '${(c['slot'] as String).split('-').first}-';
    return camel(data.startsWith(prefix) ? data.substring(prefix.length) : data);
  }
  return null;
}

/// The part slots a rule asks about (`hasSlot`) as (widget field, data-slot). The one grid this emitter
/// lays out has a single trailing part.
List<(String, String)> _parts(Map<String, dynamic> c) {
  final inputs = _inputs(c);
  final parts = [
    for (final s in (c['slots'] as List).cast<Map<String, dynamic>>())
      if (s['dataSlot'] != null && inputs.contains(_flag(c, s['dataSlot'] as String)))
        (_partField(c, s['dataSlot'] as String)!, s['dataSlot'] as String),
  ];
  if (parts.length > 1) {
    throw EmitException('${c['name']}: ${parts.length} part slots have no Flutter layout here');
  }
  return parts;
}

String _flag(Map<String, dynamic> c, String slot) {
  final field = _partField(c, slot);
  if (field == null) throw EmitException('${c['name']}: hasSlot "$slot" names no part slot');
  return 'has${_upperFirst(field)}';
}

String _condition(Map<String, dynamic> c, Map<String, dynamic> rule) {
  final when = (rule['when'] as Map).cast<String, dynamic>();
  final parts = <String>[];
  String eq(String axis, String value, String op) =>
      '$axis $op ${_enumName(c, axis)}.${enumValue(value)}';
  for (final e in when.entries) {
    switch (e.key) {
      case 'mode':
        parts.add("t.mode == '${e.value}'");
      case 'states':
        parts.addAll((e.value as List).map((s) => 'states.contains(WidgetState.$s)'));
      case 'hasIcon' || 'interactive':
        parts.add(e.key);
      case 'hasSlot':
        parts.add(_flag(c, e.value as String));
      default:
        if (!_variants(c).containsKey(e.key)) throw EmitException('unknown condition ${e.key}');
        parts.add(eq(e.key, e.value as String, '=='));
    }
  }
  for (final ex in ((rule['except'] as List?) ?? const []).cast<Map>()) {
    final terms = ex.entries.map((e) => eq(e.key as String, e.value as String, '==')).toList();
    parts.add(
      terms.length == 1
          ? eq(ex.keys.single as String, ex.values.single as String, '!=')
          : '!(${terms.join(' && ')})',
    );
  }
  return parts.join(' && ');
}

/// The inputs a component's rules use, so its resolver takes only those.
Set<String> _inputs(Map<String, dynamic> c) {
  final used = <String>{};
  for (final r in (c['rules'] as List).cast<Map<String, dynamic>>()) {
    final when = (r['when'] as Map).cast<String, dynamic>();
    for (final k in when.keys) {
      used.add(k == 'hasSlot' ? _flag(c, when[k] as String) : k);
    }
    for (final ex in ((r['except'] as List?) ?? const []).cast<Map>()) {
      used.addAll(ex.keys.cast<String>());
    }
  }
  return used;
}

/// A button, or any component whose rules ask about its state or whether it is interactive (Badge as a link).
bool _isPressable(Map<String, dynamic> c) =>
    c['role'] == 'button' ||
    c['name'] == 'Badge' ||
    _inputs(c).any(const {'states', 'interactive'}.contains);

/// The boolean inputs among a resolver's inputs: icon, then interactive, then one per part slot.
List<String> _flags(Set<String> inputs) => [
  ...['hasIcon', 'interactive'].where(inputs.contains),
  ...inputs.where((i) => i.startsWith('has') && i != 'hasIcon'),
];

bool _hasIconRules(Map<String, dynamic> c) =>
    (c['rules'] as List).cast<Map<String, dynamic>>().any((r) => r['target'] == 'icon');

String _resolver(Map<String, dynamic> c, Map<String, dynamic> globals) {
  final name = c['name'] as String;
  final rules = (c['rules'] as List).cast<Map<String, dynamic>>();
  final inputs = _inputs(c);
  final hasIcon = _hasIconRules(c);
  final named = <String>[
    for (final axis in _variants(c).keys) 'required ${_enumName(c, axis)} $axis',
    if (inputs.contains('states')) 'required Set<WidgetState> states',
    for (final flag in _flags(inputs)) 'required bool $flag',
  ];
  final ret = hasIcon ? '({DsStyle root, DsStyle icon})' : 'DsStyle';
  // A DSIR may hold no globals (an inferred one puts every cell's shared values in the component's own rules).
  final star = (((globals['*'] as Map?)?['rules']) as List?)?.cast<Map<String, dynamic>>().single;
  final starArgs = star == null ? '' : _styleArgs((star['set'] as Map).cast<String, dynamic>()).$1;
  final b = StringBuffer()
    ..writeln(
      "/// $name's cascade in CSS order (specificity, then Tailwind's stylesheet order, after",
    )
    ..writeln('/// tailwind-merge). A later line wins. Each line names the class it came from.')
    ..writeln(
      '$ret resolve${name}Style(DsTokens t${named.isEmpty ? '' : ', {${named.join(', ')}}'}) {',
    );
  b.writeln(
    '  var root = DsStyle($starArgs);${star == null ? '' : " // * { @apply ${star['from']} }"}',
  );
  if (hasIcon) b.writeln('  var icon = const DsStyle();');
  for (final r in rules) {
    final (args, isConst) = _styleArgs((r['set'] as Map).cast<String, dynamic>());
    final target = r['target'] == 'icon' ? 'icon' : 'root';
    final stmt = '$target = $target.merge(${isConst ? 'const ' : ''}DsStyle($args));';
    final cond = _condition(c, r);
    b.writeln(cond.isEmpty ? '  $stmt // ${r['from']}' : '  if ($cond) { $stmt } // ${r['from']}');
  }
  b
    ..writeln(hasIcon ? '  return (root: root, icon: icon);' : '  return root;')
    ..writeln('}');
  return b.toString();
}

String _componentFile(List<Map<String, dynamic>> group, Map<String, dynamic> globals) {
  final pressable = group.any(_isPressable);
  final b = StringBuffer()
    ..writeln('// Generated by scrib_ds from the DSIR. Do not edit.')
    ..writeln("import 'package:flutter/widgets.dart';")
    ..writeln()
    ..writeln("import '../primitives/ds_box.dart';");
  if (pressable) b.writeln("import '../primitives/ds_pressable.dart';");
  b
    ..writeln("import '../primitives/ds_style.dart';")
    ..writeln("import '../theme.dart';")
    ..writeln("import '../tokens.dart';")
    ..writeln();
  for (final c in group) {
    for (final axis in _variants(c).entries) {
      final values = (axis.value as List).cast<String>().map(enumValue).join(', ');
      b
        ..writeln('enum ${_enumName(c, axis.key)} { $values }')
        ..writeln();
    }
    b
      ..writeln(_widget(c))
      ..writeln(_resolver(c, globals));
  }
  return b.toString();
}

String _widget(Map<String, dynamic> c) {
  final name = c['name'] as String;
  final slots = (c['slots'] as List)
      .cast<Map<String, dynamic>>()
      .map((s) => s['name'] as String)
      .toSet();
  final inputs = _inputs(c);
  final parts = _parts(c);
  final part = parts.isEmpty ? null : parts.single.$1;
  final defaults = (c['defaultVariants'] as Map).cast<String, dynamic>();
  final isButton = c['role'] == 'button';
  final interactive = _isPressable(c);
  // A pressable that is not a button (Badge, a clickable tile) is a plain element until it has an `onPressed`.
  final isBadge = interactive && !isButton;
  final hasIcon = slots.contains('icon');
  final fields = <String>[];
  final ctor = <String>['super.key'];
  void field(String decl, String param, {String? doc}) {
    if (doc != null) fields.add('/// $doc');
    fields.add('final $decl;');
    ctor.add(param);
  }

  if (hasIcon)
    field(
      'Widget? icon',
      'this.icon',
      doc: 'Leading icon (the `svg` child), sized by the component.',
    );
  if (slots.contains('child')) field('Widget? child', 'this.child');
  if (slots.contains('children')) field('List<Widget> children', 'this.children = const []');
  if (part != null) {
    field(
      'Widget? $part',
      'this.$part',
      doc: 'The `data-slot="${parts.single.$2}"` child, placed in the trailing column.',
    );
  }
  for (final axis in _variants(c).keys) {
    final type = _enumName(c, axis);
    field('$type $axis', 'this.$axis = $type.${enumValue(defaults[axis] as String)}');
  }
  if (interactive) {
    field(
      'VoidCallback? onPressed',
      'this.onPressed',
      doc: isButton
          ? 'Null disables the button.'
          : 'Makes the badge a link (`asChild` with `<a>`), which enables its hover style.',
    );
    if (inputs.contains('states'))
      field('bool invalid', 'this.invalid = false', doc: '`aria-invalid`.');
    field('WidgetStatesController? statesController', 'this.statesController');
    field('FocusNode? focusNode', 'this.focusNode');
    field('bool autofocus', 'this.autofocus = false');
    field('String? semanticLabel', 'this.semanticLabel');
  }

  final named = <String>[
    for (final axis in _variants(c).keys) '$axis: $axis',
    if (inputs.contains('states')) 'states: states',
    if (inputs.contains('hasIcon')) 'hasIcon: icon != null',
    if (inputs.contains('interactive')) 'interactive: onPressed != null',
    if (part != null) 'has${_upperFirst(part)}: $part != null',
  ];
  final call = 'resolve${name}Style(t${named.isEmpty ? '' : ', ${named.join(', ')}'})';
  // A component root resets to body text; Card's parts inherit from the Card, as in CSS.
  final isRoot = !name.startsWith('Card') || name == 'Card';
  final kids = <String>[
    if (hasIcon) 'if (icon != null) icon!',
    // Layout rule 2: a label in a horizontal flex may shrink and ellipsize instead of overflowing.
    if (slots.contains('child'))
      hasIcon ? 'if (child != null) Flexible(child: child!)' : 'if (child != null) child!',
    if (slots.contains('children')) '...children',
  ];
  final box = [
    'DsBox(',
    hasIcon || _hasIconRules(c) ? 'style: style.root, icon: style.icon, ' : 'style: style, ',
    'tokens: t, ',
    if (isRoot) 'resetText: true, ',
    if (part != null) 'trailing: $part, ',
    'children: [${kids.join(', ')}])',
  ].join();

  final b = StringBuffer()
    ..writeln('/// `$name` (data-slot="${c['slot']}") from the shadcn registry.')
    ..writeln('class $name extends StatelessWidget {')
    ..writeln('  const $name({${ctor.join(', ')}});')
    ..writeln()
    ..writeln(fields.map((f) => '  $f').join('\n'))
    ..writeln()
    ..writeln('  @override')
    ..writeln('  Widget build(BuildContext context) {')
    ..writeln('    final t = DsTheme.of(context);');
  if (interactive) {
    final pressableArgs = [
      'onPressed: onPressed',
      if (inputs.contains('states')) 'error: invalid',
      'statesController: statesController',
      'focusNode: focusNode',
      'autofocus: autofocus',
      'semanticLabel: semanticLabel',
    ].join(', ');
    if (isBadge) {
      // A plain badge is a <span>: no focus, no hover, no button semantics.
      b
        ..writeln('    if (onPressed == null) {')
        ..writeln('      final states = <WidgetState>{if (invalid) WidgetState.error};')
        ..writeln('      final style = $call;')
        ..writeln('      return Semantics(label: semanticLabel, child: $box);')
        ..writeln('    }');
    }
    b
      ..writeln('    return DsPressable($pressableArgs, builder: (context, states) {')
      ..writeln('      final style = $call;')
      ..writeln('      return $box;')
      ..writeln('    });');
  } else {
    b
      ..writeln('    final style = $call;')
      ..writeln('    return $box;');
  }
  b
    ..writeln('  }')
    ..writeln('}');
  return b.toString();
}

// ---------------- oracle cells ----------------

/// The cells both renderers draw. shadcn's Button, Badge and Card have hand-written cells (below, with the
/// card examples); any other DSIR gets one per component x variant combination x state x mode.
/// shortcut: compound components (Card) need their examples written by hand, until anatomy can generate them.
List<Map<String, dynamic>> oracleCells(List<Map<String, dynamic>> components, List<String> modes) {
  final names = components.map((c) => c['name']).toSet();
  if (!names.containsAll(['Button', 'Badge', 'Card'])) return _genericCells(components, modes);
  List<String> axis(String component, String name) =>
      (_variants(components.firstWhere((c) => c['name'] == component))[name] as List)
          .cast<String>();
  final cells = <Map<String, dynamic>>[];
  for (final mode in modes) {
    for (final variant in axis('Button', 'variant')) {
      for (final size in axis('Button', 'size')) {
        for (final state in ['rest', 'hovered', 'focused', 'disabled']) {
          final iconOnly = size.startsWith('icon');
          cells.add({
            'id': 'button.$variant.$size.$state.$mode',
            'sheet': 'button',
            'mode': mode,
            'state': state,
            'node': {
              'type': 'Button',
              'variant': variant,
              'size': size,
              if (iconOnly) 'icon': true else 'text': 'Button',
            },
          });
        }
      }
    }
    for (final variant in axis('Badge', 'variant')) {
      for (final state in ['rest', 'hovered', 'focused']) {
        cells.add({
          'id': 'badge.$variant.$state.$mode',
          'sheet': 'badge',
          'mode': mode,
          'state': state,
          'node': {
            'type': 'Badge',
            'variant': variant,
            'text': 'Badge',
            'interactive': state != 'rest',
          },
        });
      }
    }
    const header = {
      'type': 'CardHeader',
      'children': [
        {'type': 'CardTitle', 'text': 'Card title'},
        {'type': 'CardDescription', 'text': 'Card description that wraps onto a second line.'},
      ],
    };
    final examples = <String, List<Map<String, dynamic>>>{
      'full': [
        header,
        {'type': 'CardContent', 'text': 'Card content.'},
        {
          'type': 'CardFooter',
          'children': [
            {'type': 'Button', 'variant': 'default', 'size': 'default', 'text': 'Save'},
          ],
        },
      ],
      'action': [
        {
          ...header,
          'action': {'type': 'Button', 'variant': 'outline', 'size': 'sm', 'text': 'Edit'},
        },
        {'type': 'CardContent', 'text': 'Card content.'},
      ],
      'content': [
        {'type': 'CardContent', 'text': 'Only content.'},
      ],
    };
    for (final e in examples.entries) {
      cells.add({
        'id': 'card.${e.key}.rest.$mode',
        'sheet': 'card',
        'mode': mode,
        'state': 'rest',
        'width': 360,
        'node': {'type': 'Card', 'children': e.value},
      });
    }
  }
  return cells;
}

/// One cell per variant combination x state x mode for every component that is not drawn inside another.
List<Map<String, dynamic>> _genericCells(
  List<Map<String, dynamic>> components,
  List<String> modes,
) {
  final inside = {
    for (final c in components)
      for (final child in ((c['anatomy'] as Map?)?['children'] as List? ?? const [])) child,
  };
  final cells = <Map<String, dynamic>>[];
  for (final mode in modes) {
    for (final c in components) {
      if (inside.contains(c['slot'])) continue;
      var combos = <Map<String, String>>[{}];
      for (final a in _variants(c).entries) {
        combos = [
          for (final combo in combos)
            for (final v in (a.value as List).cast<String>()) {...combo, a.key: v},
        ];
      }
      final role = c['role'];
      final states = role == 'button'
          ? ['rest', 'hovered', 'focused', 'disabled']
          : role == 'link'
          ? ['rest', 'hovered', 'focused']
          : ['rest'];
      final name = c['name'] as String;
      for (final combo in combos) {
        for (final state in states) {
          cells.add({
            'id': '${name.toLowerCase()}.${[...combo.values, state].join('.')}.$mode',
            'sheet': name.toLowerCase(),
            'mode': mode,
            'state': state,
            'node': {'type': name, ...combo, 'text': name, 'interactive': state != 'rest'},
          });
        }
      }
    }
  }
  return cells;
}

